#!/usr/bin/env python3
"""Build the offline icon registry from the pinned vendor icon sources."""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
KIT = ROOT / 'crates/ui-kit'
VENDOR = KIT / 'vendor/jetbrains-icons'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = json.loads((VENDOR / 'SOURCE.json').read_text())
    actual = {p.name for p in (VENDOR / 'src').glob('*.svg')}
    if actual != set(source['files']):
        raise ValueError('Vendored icon inventory differs from SOURCE.json')
    icons = {}
    for filename, digest in source['files'].items():
        raw = (VENDOR / 'src' / filename).read_bytes()
        if hashlib.sha256(raw).hexdigest() != digest:
            raise ValueError(f'Upstream source changed: {filename}')
        svg = ET.fromstring(raw)
        for node in svg.iter():
            if node.tag.split('}')[-1] in ('script', 'foreignObject', 'style', 'image'):
                raise ValueError(f'Unsupported active/external SVG content: {filename}')
            for key, value in node.attrib.items():
                if key.startswith('on') or ('href' in key and not value.startswith('#')):
                    raise ValueError(f'Unsupported SVG attribute: {filename}: {key}')
        width, height = (float(svg.attrib[key].removesuffix('px')) for key in ('width', 'height'))
        icons[Path(filename).stem] = {'width': width, 'height': height, 'svg': raw.decode()}
    metadata = {key: source[key] for key in ('revision',)}
    template = (KIT / 'icon-runtime.js').read_text()
    generated = '// Generated by scripts/build-ui-icons.py; edit the runtime template or pinned vendor source.\n' + template.replace('__JETBRAINS_ICON_DATA__', json.dumps(icons, separators=(',', ':'))).replace('__JETBRAINS_ICON_SOURCE__', json.dumps(metadata))
    outputs = {KIT / 'web/icons.js': generated}
    stale = []
    for path, content in outputs.items():
        if path.exists() and path.read_text() == content:
            continue
        stale.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.write_text(content)
    if args.check and stale:
        raise SystemExit('Stale generated icon assets: ' + ', '.join(stale))
    print(f'{len(icons)} JetBrains SVGs verified; {len(stale)} generated assets ' + ('need updates' if args.check else 'updated'))

if __name__ == '__main__':
    main()

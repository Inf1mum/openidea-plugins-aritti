#!/usr/bin/env python3
"""Generate the offline registry from pinned, unchanged OpenIDEA native icon sources."""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
ROOT=Path(__file__).resolve().parent.parent
KIT=ROOT/'crates/ui-kit'
VENDOR=KIT/'vendor/openidea-icons'
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    source=json.loads((VENDOR/'SOURCE.json').read_text());files={}
    actual={p.relative_to(VENDOR/'src').as_posix() for p in (VENDOR/'src').rglob('*.svg')}
    if actual!=set(source['files']):raise ValueError('Native icon inventory differs from SOURCE.json')
    for name,digest in source['files'].items():
        raw=(VENDOR/'src'/name).read_bytes()
        if hashlib.sha256(raw).hexdigest()!=digest:raise ValueError(f'Native source changed: {name}')
        svg=ET.fromstring(raw)
        for node in svg.iter():
            if node.tag.split('}')[-1] in ('script','foreignObject','style','image'):raise ValueError(f'Active SVG content: {name}')
            for key,value in node.attrib.items():
                if key.startswith('on') or ('href' in key and not value.startswith('#')):raise ValueError(f'External SVG content: {name}')
        files[name]=raw.decode()
    data={name:{**{variant:files[path] for variant,path in variants.items()},'keepColors':variants['light'].startswith('expui/breakpoints/')} for name,variants in source['icons'].items()}
    metadata={key:source[key] for key in ('repository','revision','release','directory')}
    runtime=(KIT/'native-icon-runtime.js').read_text().replace('__NATIVE_ICON_DATA__',json.dumps(data,separators=(',',':'))).replace('__NATIVE_ICON_SOURCE__',json.dumps(metadata))
    outputs={KIT/'web/native-icons.js':'// Generated by scripts/build-native-ui-icons.py; edit the runtime or pinned source.\n'+runtime}
    stale=[]
    for path,text in outputs.items():
        if path.exists() and path.read_text()==text:continue
        stale.append(str(path.relative_to(ROOT)))
        if not args.check:path.write_text(text)
    if args.check and stale:raise SystemExit('Stale native assets: '+', '.join(stale))
    print(f"{len(data)} native icon names, {len(files)} SVGs verified; {len(stale)} assets {'need updates' if args.check else 'updated'}")
if __name__=='__main__':main()

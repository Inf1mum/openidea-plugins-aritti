#!/usr/bin/env python3
"""Compare two captured output directories (ours vs the original plugin) after normalization.

Exit 0 only when every file is identical after normalization and no file exists on one side only.
The result is evidence for one scenario; it is never a parity claim.
"""
import argparse
import difflib
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

NORMALIZERS = ['whitespace', 'imports', 'annotation-args', 'member-order', 'quotes', 'sql', 'sql-statement-order', 'xml', 'json']
DEFAULT_NORMALIZERS = ['whitespace', 'imports', 'annotation-args', 'quotes', 'sql', 'xml', 'json']
JVM = {'.java', '.kt', '.kts'}
SQL_KEYWORDS = (
    'create table if not exists|create table|create unique index|create index|create sequence|create or replace view|create view|'
    'alter table|drop table|drop column|drop index|add column|add constraint|alter column|rename column|rename to|primary key|'
    'foreign key|references|not null|null|default|unique|check|constraint|index|on delete cascade|on delete|on update|'
    'insert into|values|update|set|delete from|select|from|where|and|or|if exists|if not exists|on|using|cascade|restrict|'
    'varchar|char|text|integer|int|bigint|smallint|boolean|bool|uuid|numeric|decimal|timestamp|date|time|serial|bigserial|'
    'auto_increment|generated always as identity|generated by default as identity|identity|as|type|to|add|drop|column|table|key'
)
SQL_KW_RE = re.compile(r'\b(?:%s)\b' % SQL_KEYWORDS, re.I)


def split_top(text, seps=','):
    """Split on seps at nesting depth 0, outside string literals."""
    parts, buf, depth, quote, i = [], [], 0, None, 0
    while i < len(text):
        c = text[i]
        if quote:
            buf.append(c)
            if c == '\\' and i + 1 < len(text):
                buf.append(text[i + 1])
                i += 1
            elif c == quote:
                quote = None
        elif c in '"\'':
            quote = c
            buf.append(c)
        elif c in '([{':
            depth += 1
            buf.append(c)
        elif c in ')]}':
            depth -= 1
            buf.append(c)
        elif c in seps and depth == 0:
            parts.append(''.join(buf))
            buf = []
        else:
            buf.append(c)
        i += 1
    parts.append(''.join(buf))
    return parts


def base(text):
    text = text.replace('\r\n', '\n').replace('\r', '\n')
    lines = [l.rstrip() for l in text.split('\n')]
    return '\n'.join(lines).rstrip('\n') + '\n'


def n_whitespace(text):
    out = []
    for line in text.split('\n'):
        line = line.strip()
        if line:
            out.append(re.sub(r'[ \t]+', ' ', line))
    return '\n'.join(out) + '\n'


def n_imports(text):
    lines = text.split('\n')
    imports = [l.strip() for l in lines if re.match(r'\s*import\s', l)]
    rest = [l for l in lines if not re.match(r'\s*import\s', l)]
    body = '\n'.join(rest)
    kept = set()
    for imp in imports:
        name = re.sub(r';$', '', imp[len('import'):].strip()).strip()
        simple = re.split(r'\s+as\s+', name)[-1].split('.')[-1]
        if simple == '*' or re.search(r'\b%s\b' % re.escape(simple), body):
            kept.add(f'import {name}')
    first = next((i for i, l in enumerate(lines) if re.match(r'\s*import\s', l)), None)
    semi = ';' if any(i.endswith(';') for i in imports) else ''
    block = [k + semi for k in sorted(kept)]
    if first is None:
        return text
    rest_idx = [i for i, l in enumerate(lines) if not re.match(r'\s*import\s', l)]
    before = [lines[i] for i in rest_idx if i < first]
    after = [lines[i] for i in rest_idx if i > first]
    after = [l for l in after]
    out = before + block + after
    return '\n'.join(out)


def n_annotation_args(text):
    out, i = [], 0
    for m in re.finditer(r'@[A-Za-z_][\w.]*\(', text):
        if m.start() < i:
            continue
        depth, j, quote = 1, m.end(), None
        while j < len(text) and depth:
            c = text[j]
            if quote:
                if c == '\\':
                    j += 1
                elif c == quote:
                    quote = None
            elif c in '"\'':
                quote = c
            elif c == '(':
                depth += 1
            elif c == ')':
                depth -= 1
            j += 1
        if depth:
            continue
        inner = text[m.end():j - 1]
        args = [a.strip() for a in split_top(inner)]
        out.append(text[i:m.end()])
        if len(args) > 1 and all(re.match(r'[A-Za-z_]\w*\s*=', a) for a in args):
            inner = ', '.join(sorted(n_annotation_args(a) for a in args))
        else:
            inner = n_annotation_args(inner)
        out.append(inner + ')')
        i = j
    out.append(text[i:])
    return ''.join(out)


def n_member_order(text):
    start = text.find('{')
    if start < 0:
        return text
    depth, quote, members, buf, i = 0, None, [], [], start + 1
    end = None
    j = start
    while j < len(text):
        c = text[j]
        if quote:
            if c == '\\':
                j += 1
            elif c == quote:
                quote = None
        elif c in '"\'':
            quote = c
        elif c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                end = j
                break
        j += 1
    if end is None:
        return text
    body = text[start + 1:end]
    depth, quote, k, cur = 0, None, 0, []
    while k < len(body):
        c = body[k]
        cur.append(c)
        if quote:
            if c == '\\' and k + 1 < len(body):
                cur.append(body[k + 1])
                k += 1
            elif c == quote:
                quote = None
        elif c in '"\'':
            quote = c
        elif c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                members.append(''.join(cur).strip())
                cur = []
        elif c == ';' and depth == 0:
            members.append(''.join(cur).strip())
            cur = []
        k += 1
    tail = ''.join(cur).strip()
    if tail:
        members.append(tail)
    members = sorted(m for m in members if m)
    return text[:start + 1] + '\n' + '\n'.join(members) + '\n' + text[end:]


def n_quotes(text, ext):
    if ext in JVM or ext == '.sql':
        return text
    return re.sub(r"'([^'\"\n]*)'", r'"\1"', text)


def n_sql(text, statement_order=False):
    text = re.sub(r'`([^`]+)`|\[([A-Za-z_][\w ]*)\]', lambda m: '"%s"' % (m.group(1) or m.group(2)), text)
    pieces = re.split(r"('(?:[^']|'')*'|\"[^\"]*\")", text)
    for idx in range(0, len(pieces), 2):
        seg = pieces[idx]
        seg = SQL_KW_RE.sub(lambda m: m.group(0).upper(), seg)
        pieces[idx] = re.sub(r'\s+', ' ', seg)
    flat = ''.join(pieces)
    stmts = [s.strip() for s in split_top(flat, ';') if s.strip()]
    stmts = [re.sub(r'\s*([(),])\s*', r'\1 ', s).replace(' )', ')').strip() for s in stmts]
    if statement_order:
        stmts.sort()
    return '\n'.join(s + ';' for s in stmts) + '\n'


def canon_xml(el, depth=0):
    attrs = ''.join(f' {k}="{v}"' for k, v in sorted(el.attrib.items()))
    text = (el.text or '').strip()
    kids = ''.join(canon_xml(c, depth + 1) for c in el)
    tail = ''
    return f'<{el.tag}{attrs}>{text}{kids}</{el.tag}>\n'


def n_xml(text):
    try:
        return canon_xml(ET.fromstring(text.encode('utf-8')))
    except ET.ParseError:
        return text


def n_json(text):
    try:
        return json.dumps(json.loads(text), sort_keys=True, indent=2, ensure_ascii=False) + '\n'
    except ValueError:
        return text


def normalize(text, ext, names, strict=False):
    names = set(names)
    text = base(text)
    if ext in JVM:
        if 'imports' in names:
            text = n_imports(text)
        if 'annotation-args' in names:
            text = n_annotation_args(text)
        if 'member-order' in names:
            text = n_member_order(text)
    if 'quotes' in names:
        text = n_quotes(text, ext)
    if ext == '.sql' and ('sql' in names or 'sql-statement-order' in names):
        text = n_sql(text, 'sql-statement-order' in names)
    if ext == '.xml' and 'xml' in names:
        text = n_xml(text)
    if ext == '.json' and 'json' in names:
        text = n_json(text)
    if 'whitespace' in names:
        text = n_whitespace(text)
    if strict:
        text = re.sub(r'\s+', '', text)
    return text


def list_files(root):
    root = Path(root)
    return {str(p.relative_to(root)): p for p in sorted(root.rglob('*')) if p.is_file()}


def read(p):
    return p.read_bytes().decode('utf-8', errors='replace')


def compare(ours, theirs, names):
    a, b = list_files(ours), list_files(theirs)
    strict_names = set(NORMALIZERS)
    results = []
    for rel in sorted(set(a) | set(b)):
        if rel not in b:
            results.append({'file': rel, 'status': 'only-ours'})
            continue
        if rel not in a:
            results.append({'file': rel, 'status': 'only-theirs'})
            continue
        ext = Path(rel).suffix.lower()
        x, y = read(a[rel]), read(b[rel])
        nx, ny = normalize(x, ext, names), normalize(y, ext, names)
        if nx == ny:
            results.append({'file': rel, 'status': 'identical'})
            continue
        sx, sy = normalize(x, ext, strict_names), normalize(y, ext, strict_names)
        kind = 'cosmetic' if sx == sy else 'semantic'
        diff = ''.join(difflib.unified_diff(nx.splitlines(True), ny.splitlines(True), f'ours/{rel}', f'theirs/{rel}'))
        results.append({'file': rel, 'status': 'different', 'classification': kind, 'diff': diff})
    return results


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--ours', required=True)
    ap.add_argument('--theirs', required=True)
    ap.add_argument('--scenario', help='scenario JSON; its "normalize" list selects normalizers')
    ap.add_argument('--normalize', help='comma list overriding the scenario/default list; known: ' + ','.join(NORMALIZERS))
    ap.add_argument('--member-order', action='store_true', help='also ignore member order in Java/Kotlin')
    ap.add_argument('--sql-statement-order', action='store_true', help='also ignore SQL statement order')
    ap.add_argument('--json', action='store_true')
    args = ap.parse_args(argv)
    names = list(DEFAULT_NORMALIZERS)
    if args.scenario:
        names = json.loads(Path(args.scenario).read_text())['normalize']
    if args.normalize:
        names = [n for n in args.normalize.split(',') if n]
    if args.member_order:
        names.append('member-order')
    if args.sql_statement_order:
        names.append('sql-statement-order')
    unknown = set(names) - set(NORMALIZERS)
    if unknown:
        ap.error(f'unknown normalizers: {sorted(unknown)}')
    for d in (args.ours, args.theirs):
        if not Path(d).is_dir():
            ap.error(f'not a directory: {d}')
    results = compare(args.ours, args.theirs, names)
    ok = bool(results) and all(r['status'] == 'identical' for r in results)
    if args.json:
        print(json.dumps({'normalizers': names, 'identicalAfterNormalization': ok, 'files': results}, indent=2))
    else:
        print(f'normalizers: {", ".join(names)}')
        print(f'{"FILE":<50} RESULT')
        for r in results:
            label = {'identical': 'identical-after-normalization', 'only-ours': 'only on our side', 'only-theirs': 'only on original side'}.get(r['status']) \
                or f'different ({r["classification"]})'
            print(f'{r["file"]:<50} {label}')
        for r in results:
            if r.get('diff'):
                print(f'\n{r["diff"]}', end='')
        if not results:
            print('no files on either side')
        print('\nThis is evidence for one scenario, not a parity claim.')
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())

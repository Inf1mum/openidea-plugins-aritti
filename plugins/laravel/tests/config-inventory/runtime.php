<?php
// Explicit acceptance only. The plugin never invokes PHP while indexing.
require getenv('LARAVEL_CONFIG_FIXTURE').'/vendor/autoload.php';
use Illuminate\Foundation\Application;
use Illuminate\Config\Repository;
use Illuminate\Support\ServiceProvider;
$dir=sys_get_temp_dir().'/openidea-config-differential-'.getmypid();
mkdir($dir);
$defaults=$dir.'/demo.php';
file_put_contents($defaults,"<?php return ['enabled'=>true,'nested'=>['timeout'=>30,'retries'=>2],'untouched'=>['value'=>9],'empty'=>['hidden'=>1]];");
$app=new Application($dir);
$app->instance('config',new Repository());
$provider=new class($app) extends ServiceProvider {public function merge(string $path,string $key):void{$this->mergeConfigFrom($path,$key);}};
$provider->merge($defaults,'demo');
assert($app['config']->get('demo.enabled')===true);
assert($app['config']->get('demo.nested.timeout')===30);
$app->instance('config',new Repository(['demo'=>['enabled'=>false,'nested'=>['timeout'=>7],'empty'=>[]]]));
$provider->merge($defaults,'demo');
assert($app['config']->get('demo.enabled')===false);
assert($app['config']->get('demo.nested.timeout')===7);
assert(!$app['config']->has('demo.nested.retries'));
assert(!$app['config']->has('demo.empty.hidden'));
assert($app['config']->get('demo.untouched.value')===9);
file_put_contents($defaults,"<?php return [5=>['value'=>1],2=>'second','label'=>'base'];");
$app->instance('config',new Repository(['demo'=>[9=>'app','label'=>'override']]));
$provider->merge($defaults,'demo');
assert($app['config']->get('demo.0.value')===1);
assert($app['config']->get('demo.1')==='second');
assert($app['config']->get('demo.2')==='app');
assert($app['config']->get('demo.label')==='override');
$cache=$dir.'/cache.php';
file_put_contents($cache,"<?php return ['stores'=>['file'=>['driver'=>'array']]];");
$config=new Repository();
$loader=new Illuminate\Foundation\Bootstrap\LoadConfiguration();
$method=new ReflectionMethod($loader,'loadConfigurationFile');
$method->invoke($loader,$config,'cache',$cache,['cache'=>['default'=>'database','stores'=>['file'=>['driver'=>'file','path'=>'hidden'],'redis'=>['driver'=>'redis']],'prefix'=>'laravel']]);
assert($config->get('cache.default')==='database');
assert($config->get('cache.stores.file.driver')==='array');
assert(!$config->has('cache.stores.file.path'));
assert($config->get('cache.stores.redis.driver')==='redis');
unlink($defaults);unlink($cache);rmdir($dir);
echo 'PASS actual Laravel '.Application::VERSION.' / PHP '.PHP_VERSION.': unpublished defaults, shallow app replacement, numeric source-order renumbering, framework option merge'.PHP_EOL;

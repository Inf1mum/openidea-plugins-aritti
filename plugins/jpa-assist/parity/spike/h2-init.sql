CREATE SCHEMA SHOP;
CREATE TABLE SHOP.CUSTOMER(ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, EMAIL VARCHAR(255) NOT NULL, NAME VARCHAR(100) DEFAULT 'anon', BALANCE DECIMAL(12,2), CONSTRAINT UQ_EMAIL UNIQUE(EMAIL));
CREATE TABLE SHOP.ORDERS(ID BIGINT PRIMARY KEY, CUSTOMER_ID BIGINT NOT NULL, PLACED TIMESTAMP, CONSTRAINT FK_CUST FOREIGN KEY(CUSTOMER_ID) REFERENCES SHOP.CUSTOMER(ID) ON DELETE CASCADE ON UPDATE RESTRICT);
CREATE INDEX IDX_ORD_PLACED ON SHOP.ORDERS(PLACED DESC, CUSTOMER_ID);
CREATE TABLE SHOP.LINE(ORDER_ID BIGINT, N INT, SKU VARCHAR(20), PRIMARY KEY(ORDER_ID, N));
COMMENT ON TABLE SHOP.CUSTOMER IS 'customers';
CREATE VIEW SHOP.V_CUST AS SELECT ID, EMAIL FROM SHOP.CUSTOMER;
